 *   돈 · 건강 · 연애를 단정하지 않는다(투자 · 병 · 고백을 권하지 않는다) — 13세 이상 앱이고 「재미로 보세요」다. 해요체 두 문장 안, 「아침」 · 「저녁」처럼 늦게 열면 지난 운이 되는 때를 약속하지 않는다.
 * - id는 검수 기록과 테스트가 가리키는 이름이다. 저장되는 것은 [DailyFortuneCatalog.fortunes]의 순번이다 — 그 KDoc의 ⚠️.
