/**
 * 명언의 장(章) — 나중에 사용자가 장별로 골라 보게 할 수 있다(사용자 2026-10-21 「고도화 여지」 — 아이디어 I-6). 지금은 화면에 쓰지 않는다.
 * ⚠️ 이름을 바꾸지 않는다 — 장별 고르기가 생기면 저장값이 된다(함정 1).
 */
internal enum class DailyQuoteChapter { GoClassics, GoProverbs, GoPlayers, EasternClassics, WesternFigures }

/**
 * 「오늘의 한 줄 명언」에 싣는 명언(백로그 #273, 사용자 2026-10-20 · 10-21).
 * 홈의 한 줄 자리에 하루 하나씩, 설치마다 한 번 섞은 차례대로 뜬다(차례와 본 기록은 `DailyQuoteStore`, 고르기는 shared의 `pickDailyQuote`).
 *
 * - **화면에는 명언과 말한 이만** 보인다. [DailyQuote.source]는 출처 기록이다 — 화면에 띄우지 않는다(사용자 2026-10-21).
 * - 4개 언어: 원문이 그 언어면 원문, 아니면 널리 쓰이는 번역, 없으면 스레드가 옮겼다(영·일·중 원어민 확인 없음).
 * - ⚠️ **id는 저장값이다** — 바꾸면 그 명언을 본 기록이 끊겨 한 번 더 나온다. 명언을 빼는 것은 괜찮다(차례에서 저절로 빠진다).
 * - ⚠️ 길이: 폰(360dp) 홈 한 줄 자리에서 **두 줄 안**(사용자 2026-10-21) — `DailyQuoteCatalogTest`가 언어마다 어림 폭을 잰다. 넘치던 번역은 줄였고,
 *   원문이 긴 몇 개는 핵심 구절만 발췌했다(스레드가 정한 것 — [DailyQuote.source]에 원문과 발췌를 적었다).
 * - 실은 범위: 후보 184개 가운데 출처를 확인하지 못한 10개를 뺀 전부(사용자 2026-10-21: *"우선 다 넣어줘"* + 첫 결정 「출처를 확인한 것만」).
 */
internal class DailyQuote(
    val id: String,
    val chapter: DailyQuoteChapter,
    val source: String,
    private val korean: QuoteLine,
    private val english: QuoteLine,
    private val japanese: QuoteLine,
    private val chinese: QuoteLine,
) {
    fun lineFor(language: UiLanguage): QuoteLine = when (language) {
        UiLanguage.Korean -> korean
        UiLanguage.English -> english
        UiLanguage.Japanese -> japanese
        UiLanguage.ChineseSimplified -> chinese
    }
}

