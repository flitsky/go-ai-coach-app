package com.worksoc.goaicoach.ui

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue

/**
 * **앱 안에서 글꼴 배율을 갈아 보는** 개발자 1차 도구의 상태(백로그 #81).
 *
 * ## 왜 읽기 전용 표시로는 부족했나
 * 처음에는 현재 배율을 **보여주기만** 했다(#77). 표시는 정확했지만(시스템에서 1.3으로 바꾸면
 * `×1.3`으로 갱신된다) **쓸 데가 없었다** — #64가 배율 관련 잘림을 네 자리에서 낳았고, 그것을
 * 재현하려면 매번 **시스템 설정을 왕복**해야 한다는 것이 원래 문제였는데 표시는 그 왕복을 줄여
 * 주지 않는다. 게다가 주변 행이 전부 조작 가능해서 **이 행도 조작하는 것으로 읽힌다**
 * (2026-09-04 사용자 제보: *"글꼴 배율을 넣어준 것 같은데 실제로 동작은 안하고 있음"*).
 *
 * ## ⚠️ 시스템 설정을 바꾸는 것이 아니다
 * 시스템 배율을 앱이 바꾸려면 `WRITE_SETTINGS`가 필요하고, 그것은 개발자 도구가 요구할 권한이
 * 아니다. 대신 **이 앱의 컴포지션에만** `LocalDensity`의 `fontScale`을 덮어쓴다 — 화면에 보이는
 * 결과는 시스템 배율을 올린 것과 같고, 앱을 나가면 아무것도 남지 않는다.
 *
 * ## ⚠️ 저장하지 않는다
 * 앱을 다시 켜면 시스템 배율로 돌아간다. 저장하면 "왜 글자가 크지?"를 나중에 디버깅하게 된다.
 *
 * ⚠️ **1차에 둬도 되는 이유**: 권한을 만들지 않고 표시만 바꾼다(#77의 분류 기준). release에
 * 실려도 사용자가 얻는 것은 큰 글자뿐이다.
 */
internal object DevFontScaleOverride {

    /** 덮어쓸 배율. `null`이면 시스템 값을 그대로 쓴다. */
    var scale by mutableStateOf<Float?>(null)
        private set

    /**
     * 다음 배율로 넘긴다 — 시스템 → 1.0 → 1.3 → 2.0 → 시스템.
     *
     * ⚠️ 세 값은 **#64가 실제로 검증한 배율**이다(그 커밋 메시지: *"1.0 / 1.30 / 2.0에서 전후를
     * 확인했다"*). 임의 슬라이더보다 이 셋을 돌리는 것이 그 회귀를 다시 밟는 데 정확하다.
     */
    fun cycle() {
        scale = when (scale) {
            null -> 1.0f
            1.0f -> 1.3f
            1.3f -> 2.0f
            else -> null
        }
    }
}
