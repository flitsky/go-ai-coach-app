package com.worksoc.goaicoach.application.preferences

/**
 * **진행 중인 대국이 있을 때 판 크기·접바둑을 잠글지** 판정한다(백로그 #75).
 *
 * ## 왜 이 판정이 함수로 나와 있는가
 * 조건이 짧지만 **틀리기 쉬운 자리**다. `isGameEnded` 하나로 판단하면 **대국을 한 번도 하지 않은
 * 사용자에게도 잠긴다** — 시작한 적이 없으면 끝난 적도 없으므로 `isGameEnded`가 `false`다.
 * 그래서 *"둔 수가 있고, 아직 끝나지 않았다"* 두 조건을 함께 본다.
 * · ⚠️ 이 조건을 화면 안에서 인라인으로 쓰면 **테스트가 닿지 않는다** — 설정 화면과 콤팩트 패널은
 *   단위 테스트가 하나도 참조하지 않는 파일이다(#76에서 확인했다). 순수 함수로 빼야 그물이 생긴다.
 *
 * ## 접바둑 돌은 "둔 수"가 아니다
 * 접바둑 5점으로 시작한 판의 `moveCount`는 **0**이다(저장을 열어 확인했다 — 접바둑 5점·1수 대국의
 * `moves`가 1이었다). 그래서 *"접바둑만 놓인 채 아직 안 둔 판"* 은 잠기지 않는다 — 그 상태에서
 * 설정을 바꾸는 것은 **다음 대국 준비**이지 진행 중 대국을 건드리는 것이 아니다.
 *
 * ## ⚠️ 화면에 없어도 **저장에 있으면** 잠근다
 * 앱을 다시 켠 직후에는 저장된 대국이 아직 메모리로 올라오지 않아 [moveCount]가 0이다
 * (홈 화면이 *"이전 대국 이어하기"* 를 띄우고 있는 그 상태다). 그때 잠기지 않으면
 * **앱을 껐다 켜는 것만으로 잠금이 우회된다** — 그리고 이어하기를 누른 순간, 이 항목이 없애려던
 * *"설정은 19x19인데 판은 13x13"* 어긋남이 그대로 재현된다(2026-09-05 실기에서 실제로 밟았다).
 * · [hasResumableSavedGame]은 `SavedGameSnapshot.isResumable`을 그대로 받는다 —
 *   ⚠️ **여기서 "진행 중"을 새로 정의하지 말 것.** 홈 화면의 *"이어하기"* 버튼이 쓰는 것과
 *   **같은 판정**이어야 한다. 둘이 갈라지면 *"이어하기는 뜨는데 잠기지는 않는"* 상태가 생긴다.
 *
 * ## ⚠️ 잠그는 것은 판 크기·접바둑 **둘뿐**이다
 * 계가 방식과 덤은 잠그지 않는다. 원래 심플 레이아웃도 그 둘만 `isGameEnded`에 묶었다 —
 * 판의 **모양**을 바꾸는 것과 **셈법**을 바꾸는 것은 진행 중 대국에 미치는 뜻이 다르다.
 */
fun isBoardSetupLockedDuringGame(
    moveCount: Int,
    isGameEnded: Boolean,
    hasResumableSavedGame: Boolean = false,
): Boolean = (moveCount > 0 && !isGameEnded) || hasResumableSavedGame
