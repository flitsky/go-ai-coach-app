package com.worksoc.goaicoach.application.profile

/**
 * 사용자가 자기 자신에게 붙이는 **닉네임의 규칙**(백로그 #165) — 몇 글자까지 받는가, 무엇을 남기는가.
 *
 * ## 왜 여기인가 (refactor backlog #85)
 * 이 규칙은 처음에 저장 어댑터(`persistence/UserProfileStore.kt`) 안에만 있었고, 입력 팝업
 * (`ui/UserNicknameDialog.kt`)이 입력 중 자르기에 **어댑터의 상수를 끌어다 썼다.** 12자 상한은 저장
 * 형식의 사정이 아니라 **제품 규칙**이라(아래 [MaxLength]) 위 계층에 있어야 한다 — 원칙 문서 4계층
 * "포트가 아는 것" ⓑ의 *"위 계층에 있어야 할 규칙을 어댑터 안에 쓰는 것"* 이 그 모양이었다.
 * 이제 저장소(저장 전)와 팝업(입력 중)이 둘 다 이 객체를 **부르기만** 한다. 옮기면서 동작은 바꾸지
 * 않았다 — 같은 입력이 같은 저장값·같은 입력 중 상한을 낸다(`UserProfileStoreTest`·
 * `UserNicknamePolicyTest`의 고정표).
 *
 * ## ⚠️ 두 함수가 다르다 — 입력 중에는 공백을 걷지 않는다
 * [capInput]은 팝업이 **글자를 칠 때마다** 부른다. 거기서 공백을 걷으면 끝에 친 띄어쓰기가 곧바로
 * 사라져 *"바둑 이"* 같은 이름을 칠 수 없다. 걷기와 빈 값 접기는 확인을 누른 뒤 [sanitize]가 한다.
 * 상한은 둘이 **같은 [MaxLength]** 를 쓴다 — 다르면 13번째 글자가 보이다가 저장하면 사라진다.
 */
object UserNicknamePolicy {

    /**
     * 닉네임 길이 상한. **글자 수이지 바이트가 아니다** — 한글·한자 한 글자도 1로 센다.
     * ⚠️ 상한이 있는 이유는 저장 용량이 아니라 **한 줄에 들어가야 하기 때문**이다(함정 21:
     * CJK는 폭이 두 배다). 늘릴 때는 마이 페이지를 네 언어로 다시 볼 것.
     *
     * ⚠️ 정확히는 **UTF-16 코드 단위**로 센다(`String.take`) — 기본 다국어 평면 밖의 글자(이모지
     * 대부분)는 2로 세고, 12번째 단위가 서로게이트 쌍의 앞 반쪽이면 그 반쪽까지만 남는다.
     */
    const val MaxLength: Int = 12

    /** 입력 중인 글자를 상한까지만 자른다. 걷지 않는다(위 머리말). */
    fun capInput(input: String): String = input.take(MaxLength)

    /**
     * 저장할 닉네임. 앞뒤 공백을 걷은 **뒤** 상한까지 자르고, 남는 것이 없으면 `null`이다.
     *
     * ⚠️ **`null`은 지우라는 뜻이다** — 사용자가 다 지우고 확인하면 「이름 없음」으로 되돌아가야 한다.
     * 빈 문자열을 그대로 저장하면 원 안에 아무것도 없는 아바타가 남는다.
     */
    fun sanitize(raw: String): String? = capInput(raw.trim()).takeIf { it.isNotBlank() }
}
